import { esc, api, safeUrl, isUnlocked, toast, loading, renderMarkdown, lockedHint } from "../../shared.js";

const FORM_LABEL = { "10-K": "Annual report", "10-Q": "Quarterly report", "8-K": "Current report (material event)" };

function summaryBlock(s) {
  return `
    <div class="ai-summary">
      ${renderMarkdown(s.summary)}
      <p class="muted small ai-meta">AI-generated by ${esc(s.model || "Claude")} from ${esc(s.sections?.join(", ") || "the filing")} on ${esc((s.generatedAt || "").slice(0, 10))}. Verify figures against the filing before citing them.</p>
    </div>`;
}

export async function render(c, { symbol }) {
  c.innerHTML = loading("Loading SEC filings…");
  let data;
  try {
    data = await api(`/api/research/${encodeURIComponent(symbol)}/filings`);
  } catch (err) {
    c.innerHTML = `<p class="muted page-pad">Couldn't load filings: ${esc(err.message)}</p>`;
    return;
  }
  if (!data.filings.length) {
    c.innerHTML = `<p class="muted page-pad">No 10-K, 10-Q or 8-K filings found for ${esc(symbol)} on SEC EDGAR${data.error ? ` (${esc(data.error)})` : ""}.</p>`;
    return;
  }
  const unlocked = isUnlocked();
  c.innerHTML = `
    <section class="panel page-pad-panel" aria-labelledby="fil-h">
      <div class="panel-head"><h3 id="fil-h">Recent SEC filings</h3><span class="muted small">From EDGAR</span></div>
      ${!data.aiEnabled ? `<p class="notice small">AI filing briefs are off: the server needs an <code>ANTHROPIC_API_KEY</code>. Filings are still linked below.</p>`
        : !unlocked ? lockedHint("Unlock editing to generate AI briefs (each costs a few cents of API credit; existing briefs are free to read).") : ""}
      <ol class="filing-list">
        ${data.filings.map((f) => `
          <li class="filing" data-acc="${esc(f.accession)}">
            <div class="filing-head">
              <span class="form-pill">${esc(f.form)}</span>
              <div>
                <a href="${safeUrl(f.url)}" target="_blank" rel="noopener"><strong>${esc(FORM_LABEL[f.form] || f.form)}</strong><span class="sr-only"> (opens SEC.gov in new tab)</span></a>
                <div class="muted small">Filed ${esc(f.filingDate)}${f.reportDate ? ` · period ${esc(f.reportDate)}` : ""}${f.items ? ` · items ${esc(f.items)}` : ""}</div>
              </div>
              <div class="filing-actions">
                ${f.summary ? `<button type="button" class="btn btn-ghost btn-sm" data-toggle aria-expanded="false">Show AI brief</button>`
                  : data.aiEnabled && unlocked ? `<button type="button" class="btn btn-ghost btn-sm" data-summarize>Summarize with Claude</button>` : ""}
              </div>
            </div>
            <div class="filing-body" hidden>${f.summary ? summaryBlock(f.summary) : ""}</div>
          </li>`).join("")}
      </ol>
    </section>`;

  c.querySelector(".filing-list").addEventListener("click", async (e) => {
    const li = e.target.closest(".filing");
    if (!li) return;
    const body = li.querySelector(".filing-body");
    if (e.target.closest("[data-toggle]")) {
      const btn = e.target.closest("[data-toggle]");
      const open = body.hidden;
      body.hidden = !open;
      btn.setAttribute("aria-expanded", String(open));
      btn.textContent = open ? "Hide AI brief" : "Show AI brief";
      return;
    }
    const btn = e.target.closest("[data-summarize]");
    if (!btn) return;
    btn.disabled = true;
    btn.textContent = "Reading the filing… (up to a minute)";
    body.hidden = false;
    body.innerHTML = loading("Claude is reading the risk factors and MD&A…");
    try {
      const s = await api(`/api/research/${encodeURIComponent(symbol)}/filings/${encodeURIComponent(li.dataset.acc)}/summary`, { method: "POST" });
      body.innerHTML = summaryBlock(s);
      btn.outerHTML = `<button type="button" class="btn btn-ghost btn-sm" data-toggle aria-expanded="true">Hide AI brief</button>`;
      toast("Brief ready.", { type: "success" });
    } catch (err) {
      body.innerHTML = `<p class="error">${esc(err.message)}</p>`;
      btn.disabled = false;
      btn.textContent = "Try again";
    }
  });
}
